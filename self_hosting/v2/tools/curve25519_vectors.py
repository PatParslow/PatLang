"""Write self_hosting/v2/spec/fixtures/cv_vectors.patlang, the test vectors
the curve25519 fixtures read, from RFC 8032's text and Wycheproof's
x25519_test.json and ed25519_test.json (testvectors_v1).

    py -3 -I self_hosting/v2/tools/curve25519_vectors.py RFC8032.txt X25519.json ED25519.json

Each list is split into functions of at most 100 entries.
"""
import json
import re
import sys

OUT = "self_hosting/v2/spec/fixtures/cv_vectors.patlang"


def rfc8032_tests(path):
    lines = open(path, encoding="utf-8").read().split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith("7.1.  Test Vectors for Ed25519"))
    end = next(i for i, l in enumerate(lines) if l.startswith("7.2.  Test Vectors for Ed25519ctx"))
    tests, cur, field = [], None, None
    for l in lines[start:end]:
        s = l.strip()
        m = re.match(r"-----(TEST .+)$", s)
        if m:
            cur = {"name": m.group(1), "SECRET KEY": "", "PUBLIC KEY": "", "MESSAGE": "", "SIGNATURE": ""}
            tests.append(cur)
            field = None
            continue
        if cur is None:
            continue
        for label in ("SECRET KEY", "PUBLIC KEY", "MESSAGE", "SIGNATURE"):
            if s.startswith(label):
                field = label
                break
        else:
            if s.startswith("ALGORITHM") or s == "Ed25519":
                field = None
            elif field and re.fullmatch(r"[0-9a-f]+", s):
                cur[field] += s
    return [[t["name"], t["SECRET KEY"], t["PUBLIC KEY"], t["MESSAGE"], t["SIGNATURE"]] for t in tests]


def lit(v):
    if isinstance(v, int):
        return str(v)
    assert '"' not in v and "\\" not in v
    return '"' + v + '"'


def functions(name, rows, note):
    out = []
    parts = [rows[i:i + 100] for i in range(0, len(rows), 100)]
    for k, part in enumerate(parts):
        out.append("make a function called %s_%d returns rows" % (name, k))
        out.append("  let rows = [" + ", ".join("[" + ", ".join(lit(v) for v in r) + "]" for r in part) + "]")
        out.append("  return rows")
        out.append("end")
        out.append("")
    out.append("# " + note)
    out.append("make a function called %s returns rows" % name)
    out.append("  let rows = []")
    for k in range(len(parts)):
        out.append("  let part = %s_%d()" % (name, k))
        out.append("  let i = 0")
        out.append("  while i < list_len(part) do")
        out.append("    let rows = list_push(rows, part[i])")
        out.append("    let i = i + 1")
        out.append("  end")
    out.append("  ensure list_len(rows) == %d" % len(rows))
    out.append("  return rows")
    out.append("end")
    out.append("")
    return out


def main(rfc8032, x25519, ed25519):
    rfc = rfc8032_tests(rfc8032)
    xj = json.load(open(x25519))
    ej = json.load(open(ed25519))
    xrows = [[t["tcId"], t["private"], t["public"], t["shared"], t["result"]]
             for g in xj["testGroups"] for t in g["tests"]]
    erows = [[t["tcId"], g["publicKey"]["pk"], t["msg"], t["sig"], t["result"]]
             for g in ej["testGroups"] for t in g["tests"]]
    assert len(xrows) == xj["numberOfTests"] and len(erows) == ej["numberOfTests"]
    out = ["# Generated by self_hosting/v2/tools/curve25519_vectors.py: the test vectors",
           "# of RFC 8032 section 7.1 and of Wycheproof's x25519_test.json and",
           "# ed25519_test.json (testvectors_v1). Do not edit.",
           ""]
    out += functions("cv_rfc8032", rfc, "RFC 8032 section 7.1: [name, secret key, public key, message, signature].")
    out += functions("cv_wy_x25519", xrows, "Wycheproof X25519: [tcId, private, public, shared, result].")
    out += functions("cv_wy_ed25519", erows, "Wycheproof Ed25519: [tcId, public key, message, signature, result].")
    open(OUT, "w", newline="\n").write("\n".join(out))
    print("%s: %d RFC 8032, %d X25519, %d Ed25519" % (OUT, len(rfc), len(xrows), len(erows)))


if __name__ == "__main__":
    main(*sys.argv[1:4])
